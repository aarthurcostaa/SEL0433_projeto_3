void i2c_init(void) {
    i2c_config_t i2c_conf = {0};
    i2c_conf.mode = I2C_MODE_MASTER;
    i2c_conf.sda_io_num = PIN_SDA;
    i2c_conf.scl_io_num = PIN_SCL;
    i2c_conf.sda_pullup_en = GPIO_PULLUP_ENABLE;
    i2c_conf.scl_pullup_en = GPIO_PULLUP_ENABLE;
    i2c_conf.master.clk_speed = 400000;
    i2c_param_config(I2C_PORT, &i2c_conf);
    i2c_driver_install(I2C_PORT, i2c_conf.mode, 0, 0, 0);
}

void oled_cmd(uint8_t cmd) {
    uint8_t data[2] = {0x00, cmd};
    i2c_master_write_to_device(I2C_PORT, OLED_ADDR, data, 2, pdMS_TO_TICKS(10));
}

void oled_clear(void) {
    uint8_t block[129];
    block[0] = 0x40; // Modo dados
    memset(&block[1], 0, 128);
    for(int page = 0; page < 8; page++) {
        oled_cmd(0xB0 + page);
        oled_cmd(0x00);
        oled_cmd(0x10);
        i2c_master_write_to_device(I2C_PORT, OLED_ADDR, block, 129, pdMS_TO_TICKS(10));
    }
}

void oled_init(void) {
    uint8_t init_cmds[] = {
        0xAE, 0x20, 0x00, 0xC8, 0x00, 0x10, 0x40, 0x81, 0xFF, 
        0xA1, 0xA6, 0xA8, 0x3F, 0xA4, 0xD3, 0x00, 0xD5, 0x80, 
        0xD9, 0x22, 0xDA, 0x12, 0xDB, 0x20, 0x8D, 0x14, 0xAF
    };
    for (int i = 0; i < sizeof(init_cmds); i++) oled_cmd(init_cmds[i]);
    oled_clear();
}

void oled_set_cursor(uint8_t page, uint8_t col) {
    oled_cmd(0xB0 + page);          
    oled_cmd(0x00 | (col & 0x0F));  
    oled_cmd(0x10 | (col >> 4));    
}

void oled_print(const char* str) {
    while(*str) {
        if (*str >= 32 && *str <= 126) {
            int idx = (*str - 32) * 5;
            uint8_t data[7];
            data[0] = 0x40; // Byte de controle para escrever dados
            for(int i = 0; i < 5; i++) data[i+1] = font5x8[idx + i];
            data[6] = 0x00; // 1 pixel de espaço em branco entre as letras
            i2c_master_write_to_device(I2C_PORT, OLED_ADDR, data, 7, pdMS_TO_TICKS(10));
        }
        str++;
    }
}

uint32_t mapear_adc_para_duty(int valor_adc) {
    return DUTY_MIN + ((DUTY_MAX - DUTY_MIN) * valor_adc) / 4095;
}

void app_main(void) {
    i2c_init();
    oled_init();
    init_button(); 

    oled_set_cursor(2, 20); // Página 2, Coluna 20
    oled_print("Iniciando...");
    vTaskDelay(pdMS_TO_TICKS(1000));
    oled_clear();

    adc_oneshot_unit_init_cfg_t init_config = { .unit_id = ADC_UNIT_1 };
    adc_oneshot_new_unit(&init_config, &adc1_handle);

    adc_oneshot_chan_cfg_t config = {
        .bitwidth = ADC_BITWIDTH_12,
        .atten = ADC_ATTEN_DB_12,
    };
    adc_oneshot_config_channel(adc1_handle, PIN_POT, &config);

    ledc_timer_config_t ledc_timer = {
        .speed_mode       = SERVO_MODE,
        .timer_num        = SERVO_TIMER,
        .duty_resolution  = SERVO_RESOLUTION,
        .freq_hz          = SERVO_FREQ_HZ,
        .clk_cfg          = LEDC_AUTO_CLK
    };
    ledc_timer_config(&ledc_timer);

    ledc_channel_config_t ledc_channel = {
        .speed_mode     = SERVO_MODE,
        .channel        = SERVO_CHANNEL,
        .timer_sel      = SERVO_TIMER,
        .intr_type      = LEDC_INTR_DISABLE,
        .gpio_num       = PIN_SERVO,
        .duty           = 0, 
        .hpoint         = 0
    };
    ledc_channel_config(&ledc_channel);

    int valor_adc = 0;
    uint32_t duty_cycle = 0;
    int angulo_graus = 0;
    char buffer_oled[32]; 

    while (1) {
        if (!modo_fixo_90) {
            oled_set_cursor(2, 0); 
            oled_print("Modo: MANUAL    "); 

            adc_oneshot_read(adc1_handle, PIN_POT, &valor_adc);
            if (valor_adc < 0) valor_adc = 0; 

            duty_cycle = mapear_adc_para_duty(valor_adc);
            angulo_graus = (valor_adc * 180) / 4095;
            
        } else {
            oled_set_cursor(2, 0);
            oled_print("Modo: FIXO 90   "); 

            angulo_graus = 90;
            duty_cycle = DUTY_MIN + ((DUTY_MAX - DUTY_MIN) * 90) / 180;
        }

        ledc_set_duty(SERVO_MODE, SERVO_CHANNEL, duty_cycle);
        ledc_update_duty(SERVO_MODE, SERVO_CHANNEL);

        snprintf(buffer_oled, sizeof(buffer_oled), "Angulo: %3d     ", angulo_graus);
        oled_set_cursor(5, 0); 
        oled_print(buffer_oled);

        vTaskDelay(pdMS_TO_TICKS(100)); 
    }
}